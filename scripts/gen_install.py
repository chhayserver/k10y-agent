"""Generate the single-file installers from deploy/k8s/*.yaml.

    python scripts/gen_install.py 1.1.0

writes deploy/install/install.yaml (monitoring + control) and
deploy/install/install-readonly.yaml (monitoring only). Users run:

    kubectl apply -f install.yaml
"""

import copy
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
K8S = ROOT / "deploy" / "k8s"
OUT = ROOT / "deploy" / "install"
NAMESPACE = "k10y"
TOKEN_SECRET = "k10y-agent"


def load(name):
    return [d for d in yaml.safe_load_all((K8S / name).read_text()) if d]


def labelled(doc, version):
    doc = copy.deepcopy(doc)
    labels = doc.setdefault("metadata", {}).setdefault("labels", {})
    labels.update({"app.kubernetes.io/name": "k10y-agent", "app.kubernetes.io/version": version})
    return doc


def agent_docs(version, control):
    deployment, service = load("agent.yaml")
    container = deployment["spec"]["template"]["spec"]["containers"][0]
    container["image"] = f"docker.io/k10y/k10y-agent:{version}"
    # No ConfigMap/Secret prerequisites: plain values, and the agent creates its own token.
    container["env"] = [
        # Optional ConfigMap the installer never creates, so upgrades keep the name.
        {"name": "K10Y_CLUSTER_NAME", "valueFrom": {"configMapKeyRef": {"name": "k10y-settings", "key": "cluster-name", "optional": True}}},
        {"name": "K10Y_TOKEN_SECRET", "value": TOKEN_SECRET},
        {"name": "K10Y_CONTROL_ENABLED", "value": "true" if control else "false"},
        {"name": "K10Y_PROTECTED_NAMESPACES", "value": "kube-system,k10y"},
        {"name": "K10Y_AUDIT_PATH", "value": "/data/audit.jsonl"},
    ]
    return [deployment, service]


def build(version, control):
    rbac = load("rbac.yaml")
    docs = rbac + load("rbac-self.yaml")
    if control:
        docs += load("rbac-control.yaml")
    docs += agent_docs(version, control)
    variant = "monitoring + control" if control else "read-only monitoring"
    header = f"""# k10y-agent {version} ({variant})
# https://github.com/zorouzumaki1111-cmd/k10y-agent
#
# Install:      kubectl apply -f <this file>
# Get token:    kubectl -n k10y get secret k10y-agent -o jsonpath='{{.data.api-token}}' | base64 -d; echo
# Name cluster: kubectl -n k10y create configmap k10y-settings --from-literal=cluster-name=<name>
#               kubectl -n k10y rollout restart deploy/k10y-agent
# Open:         http://<any-node-ip>:30800   (or add it to a standalone dashboard)
# Uninstall:    kubectl delete -f <this file>
#
# Generated by scripts/gen_install.py from deploy/k8s/*.yaml. Do not edit by hand.
"""
    body = yaml.safe_dump_all([labelled(d, version) for d in docs], sort_keys=False, explicit_start=True)
    return header + body


def main():
    version = sys.argv[1] if len(sys.argv) > 1 else "latest"
    OUT.mkdir(parents=True, exist_ok=True)
    for name, control in (("install.yaml", True), ("install-readonly.yaml", False)):
        (OUT / name).write_text(build(version, control))
        print(f"wrote {OUT / name}")


if __name__ == "__main__":
    main()
